"""Writes crowdtune/src/graph_gate.inc: the men's applause (group 2) records of the stock crowdren1
graph, and which of them CrowdTune keeps for big moments only (it applies this in memory, so the
stock crowd.iff works). Gated: standing up while clapping (stsd_*) and seated high claps / hands up."""
import graph,struct,os
I,ids=graph.load()
f=[f for f in I['files'] if f['meta']['name']=='crowdren1'][0]; b=bytes(I['secs'][0]['data'][f['offs'][0]:f['offs'][0]+f['meta']['size']])
rec,_=graph.parse(b,ids)
dest=lambda n:n.split('_')[-1]
def gated(r):
    if r['grp']==2: return r['name'].startswith('stsd_') or (r['name'].startswith('stst_') and ('hiclp' in dest(r['name']) or 'hup' in dest(r['name'])))
    # seated "disappointed" (group 4): outside big moments only hands-on-head / head-in-hands poses
    # (head1, head2, pain1, pain2) - no shaking heads, yelling or arms thrown up
    if r['name'].startswith(('st_','sd_')): return False      # loops are never gated (a fan in that pose can keep it)
    return not dest(r['name']).startswith(('head','pain'))
g2=[r for r in rec if r['grp'] in (2,4)]
anim=lambda r: struct.unpack_from('<I',b,r['o'])[0]
L=['/* generated by crowd/make_gate_inc.py from the stock crowd.iff (crowdren1, 601 records):',
   '   men applause (group 2) and seated disappointed (group 4) records: {record index, 1 = big moments only, group, anim id} */',
   'static const struct { unsigned short i; unsigned char gated, grp; unsigned int anim; } k_g2[] = {']
L+=['    { %d, %d, %d, 0x%08X }, /* %s */'%(r['i'],1 if gated(r) else 0,r['grp'],anim(r),r['name']) for r in g2]
L.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','src','graph_gate.inc'),'w').write('\n'.join(L)+'\n')
print(len(g2),'records,',sum(gated(r) for r in g2),'gated')
